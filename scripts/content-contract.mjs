import { readFile, writeFile } from 'node:fs/promises';
import { spawnSync } from 'node:child_process';
import { format } from 'prettier';

// 字段由同一份契约生成，运行 --check 可防止 Go 与两端 TypeScript 漂移。
const definitions = JSON.parse(await readFile('contracts/content-model.json', 'utf8'));
const platforms = JSON.parse(await readFile('apps/api/content_platforms.json', 'utf8'));
const name = (field) =>
  field
    .split('_')
    .map(
      (part) =>
        ({ id: 'ID', ttl: 'TTL', urls: 'URLs', html: 'HTML' })[part] ||
        part[0].toUpperCase() + part.slice(1),
    )
    .join('');
function type(value, go = false) {
  if (value.endsWith('?'))
    return go ? '*' + type(value.slice(0, -1), true) : type(value.slice(0, -1)) + ' | null';
  if (value.endsWith('[]'))
    return go ? '[]' + type(value.slice(0, -2), true) : type(value.slice(0, -2)) + '[]';
  if (value.startsWith('map:'))
    return go
      ? 'map[string]' + type(value.slice(4), true)
      : 'Record<string, ' + type(value.slice(4)) + '>';
  return (
    (go
      ? {
          string: 'string',
          boolean: 'bool',
          number: 'float64',
          integer: 'int64',
          json: 'json.RawMessage',
        }
      : { json: 'Record<string, unknown>', integer: 'number' })[value] || value
  );
}
let go =
  '// Code generated by scripts/content-contract.mjs; DO NOT EDIT.\npackage bridge\nimport "encoding/json"\n';
let ts = '// 由 scripts/content-contract.mjs 生成，请修改 contracts/content-model.json。\n';
for (const [model, fields] of Object.entries(definitions)) {
  go += `type ${model} struct {\n`;
  ts += `export interface ${model} {\n`;
  for (const [field, value] of Object.entries(fields)) {
    go += `${name(field)} ${type(value, true)} \`json:"${field}"\`\n`;
    ts += `${field}: ${type(value)};\n`;
  }
  go += '}\n';
  ts += '}\n';
}
ts += `export const contentPlatforms: readonly ContentPlatform[] = ${JSON.stringify(platforms)};\n`;
const formatted = spawnSync('gofmt', [], { input: go, encoding: 'utf8' });
if (formatted.error || formatted.status !== 0) throw Error('无法格式化 Go 内容契约');
ts = await format(ts, {
  ...JSON.parse(await readFile('.prettierrc.json', 'utf8')),
  parser: 'typescript',
});
for (const [path, value] of [
  ['apps/api/content_contract.go', formatted.stdout],
  ['apps/worker/src/content-contract.ts', ts],
  ['apps/admin/src/content-contract.ts', ts],
]) {
  if (process.argv.includes('--check')) {
    if ((await readFile(path, 'utf8')) !== value) throw Error(`${path} 与内容契约不同步`);
  } else await writeFile(path, value, 'utf8');
}
